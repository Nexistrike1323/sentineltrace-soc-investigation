"""JSON and Markdown report generation."""

import json
from pathlib import Path

from sentineltrace.detections import Finding


RECOMMENDATIONS = {
    "ST-001": [
        "Verify whether the successful login was authorized.",
        "Review the account's recent authentication history.",
        "Check the source IP against approved network ranges.",
        "Review related endpoint and identity-provider telemetry.",
    ],
    "ST-002": [
        "Inspect the complete PowerShell command line.",
        "Review parent process, user context, and process execution time.",
        "Check referenced URLs and downloaded files using approved tools.",
        "Correlate with endpoint and network telemetry.",
    ],
}


def build_report(findings: list[Finding]) -> dict:
    """Build a structured investigation report."""
    return {
        "report_name": "SentinelTrace SOC Investigation Report",
        "schema_version": "1.0",
        "finding_count": len(findings),
        "findings": [
            {
                **finding.to_dict(),
                "recommendations": RECOMMENDATIONS.get(
                    finding.rule_id,
                    ["Review the event evidence and investigate further."],
                ),
            }
            for finding in findings
        ],
    }


def write_json_report(findings: list[Finding], output_dir: str | Path) -> Path:
    output = Path(output_dir)
    output.mkdir(parents=True, exist_ok=True)

    report_path = output / "sentineltrace_report.json"
    report = build_report(findings)

    report_path.write_text(
        json.dumps(report, indent=2, ensure_ascii=False),
        encoding="utf-8",
    )
    return report_path


def write_markdown_report(
    findings: list[Finding],
    output_dir: str | Path,
) -> Path:
    output = Path(output_dir)
    output.mkdir(parents=True, exist_ok=True)

    lines = [
        "# SentinelTrace SOC Investigation Report",
        "",
        f"**Total findings:** {len(findings)}",
        "",
        "> Findings are detection leads, not proof of compromise. "
        "Analyst validation is required.",
        "",
    ]

    if not findings:
        lines.extend([
            "## Result",
            "",
            "No findings were generated by the enabled detection rules.",
            "",
        ])

    for index, finding in enumerate(findings, start=1):
        lines.extend([
            f"## {index}. {finding.title}",
            "",
            f"- **Rule:** {finding.rule_id}",
            f"- **Severity:** {finding.severity}",
            f"- **Confidence:** {finding.confidence}",
            f"- **Host:** {finding.host}",
            f"- **Username:** {finding.username or 'Not available'}",
            f"- **Source IP:** {finding.source_ip or 'Not available'}",
            f"- **First seen:** {finding.first_seen}",
            f"- **Last seen:** {finding.last_seen}",
            "",
            "### Description",
            "",
            finding.description,
            "",
            "### Evidence",
            "",
        ])

        for evidence in finding.evidence:
            lines.extend([
                f"- Event ID: `{evidence.get('event_id', 'unknown')}`",
                f"  - Timestamp: `{evidence.get('timestamp', 'unknown')}`",
                f"  - Fingerprint: `{evidence.get('fingerprint', 'unknown')}`",
            ])

            if evidence.get("command_line"):
                lines.append(
                    f"  - Command line: `{evidence['command_line']}`"
                )

        lines.extend([
            "",
            "### Analyst recommendations",
            "",
        ])

        for recommendation in RECOMMENDATIONS.get(
            finding.rule_id,
            ["Review the event evidence and investigate further."],
        ):
            lines.append(f"- {recommendation}")

        lines.append("")

    report_path = output / "sentineltrace_report.md"
    report_path.write_text("\n".join(lines), encoding="utf-8")
    return report_path
